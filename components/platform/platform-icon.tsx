const normalize = (s: string) => s.toLowerCase().replace(/icon$/i, '').replace(/[^a-z0-9]/g, '')
const NORMALIZED = new Map<string, LucideIcon>(
  Object.entries(ICONS).map(([k, v]) => [normalize(k), v]),
)

export function resolveIcon(name?: string | null, hint?: string | null): LucideIcon {
  const raw = String(name ?? '').trim()
  if (raw) {
    if (ICONS[raw]) return ICONS[raw]
    const n = normalize(raw)
    const hit = NORMALIZED.get(n) ?? ALIASES[n]
    if (hit) return hit
  }
  const haystack = `${raw} ${hint ?? ''}`.toLowerCase()
  for (const [re, icon] of KEYWORDS) if (re.test(haystack)) return icon
  return Layers
}

export function PlatformIcon({
  name,
  hint,
  ...props
}: { name?: string | null; hint?: string | null } & Omit<LucideProps, 'ref'>) {
  const Icon = resolveIcon(name, hint)
  return <Icon aria-hidden {...props} />
}
